/**
 * Русские тексты.
 *
 * **Переводчику достаточно одного этого файла.** Читать код не нужно.
 *
 * Два правила (`docs/국제화.md`, глава 3):
 *
 * 1. **Не собирать фразу из кусков.** Место для значения — `{name}`, всё
 *    остальное — законченное предложение на этом языке. Иначе перевод на язык
 *    с другим порядком слов невозможен.
 * 2. **Корейские частицы решаются только внутри корейского.** В русском их нет,
 *    но есть три формы числа — для них ниже есть `plural`.
 *
 * Тип `Record<MessageKey, Message>` означает, что ключ, который есть в `ko.ts`,
 * но отсутствует здесь, — **ошибка компиляции**, а не пустое место на экране.
 *
 * ---
 *
 * **Внимание — перевод не проверен носителем языка.** Перед выпуском в русскоязычных
 * странах его должен прочитать человек, для которого русский родной. В приложении,
 * которому доверяют пароли, одна неловкая формулировка стоит доверия.
 *
 * Слова выбраны так же, как в корейской версии: простые, без специальных терминов
 * (спецификация, глава 3). «Открыть», а не «расшифровать».
 */

/**
 * Три формы числа: 1 запись, 2 записи, 5 записей.
 *
 * Какая форма нужна — знает `Intl.PluralRules`. Своими руками это писать нельзя:
 * 21 — это «one», а 11 — «many», и такие правила легко перепутать.
 */
function plural(n: unknown, one: string, few: string, many: string): string {
  const form = pluralKey('ru', Number(n));
  if (form === 'one') return one;
  if (form === 'few') return few;
  return many;
}

